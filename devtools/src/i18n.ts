const messages: Record<string, Record<string, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
  ...extraLocales,
  ...extraLocales2,
};

export const SUPPORTED_LOCALES = [
  "zh-CN", "en-US", "zh-TW", "ja", "ko", "es",
  "fr", "de", "pt-BR", "ru", "ar", "hi",
];

export const LOCALE_LABELS: Record<string, string> = {
  "zh-CN": "简体中文", "en-US": "English", "zh-TW": "繁體中文",
  "ja": "日本語", "ko": "한국어", "es": "Español",
  "fr": "Français", "de": "Deutsch", "pt-BR": "Português (BR)",
  "ru": "Русский", "ar": "العربية", "hi": "हिन्दी",
};

let currentLocale = "zh-CN";

export function initLocale() {
  const saved = localStorage.getItem("hap-devtools-locale");
  if (saved && messages[saved]) {
    currentLocale = saved;
    return;
  }
  const sysLang = navigator.language;
  if (messages[sysLang]) {
    currentLocale = sysLang;
  } else if (sysLang.startsWith("zh")) {
    currentLocale = sysLang.includes("TW") || sysLang.includes("HK") ? "zh-TW" : "zh-CN";
  } else {
    const base = sysLang.split("-")[0];
    const match = SUPPORTED_LOCALES.find(l => l.startsWith(base));
    currentLocale = match || "en-US";
  }
}

export function setLocale(locale: string) {
  currentLocale = locale;
  localStorage.setItem("hap-devtools-locale", locale);
}

export function getLocale() {
  return currentLocale;
}

export function t(key: string): string {
  return messages[currentLocale]?.[key] ?? messages["en-US"]?.[key] ?? key;
}
