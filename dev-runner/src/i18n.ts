import { propTranslations } from './i18n-props';

for (const [locale, props] of Object.entries(propTranslations)) {
  if (translations[locale]) {
    Object.assign(translations[locale], props);
  }
}

let currentLocale = 'en-US';

export function getLocale(): string {
  try {
    const s = localStorage.getItem('hap-locale');
    if (s && translations[s]) return s;
  } catch {}
  const lang = navigator.language || 'en-US';
  if (translations[lang]) return lang;
  const prefix = lang.split('-')[0];
  for (const k of Object.keys(translations)) {
    if (k.startsWith(prefix)) return k;
  }
  return 'en-US';
}

export function setLocale(l: string) {
  currentLocale = l;
  try { localStorage.setItem('hap-locale', l); } catch {}
}

export function t(key: string): string {
  return translations[currentLocale]?.[key] || translations['en-US']?.[key] || key;
}

currentLocale = getLocale();
